"""rules_lint.py - check the global rule files and (optionally) write rules/00_INDEX.md.

Usage:
  python rules_lint.py [--rules DIR] [--write-index]
Checks every "### <ID> <title>" block in rules/0*.md:
  - has MUST or MUST NOT, Why, Check, Source, Status lines
  - Status is one of ENFORCED / CHECKLIST / PROPOSED / SEED
  - ENFORCED rules name at least one script (*.py / *.ps1) in Check, and every named script exists
    in tools/scripts, tools/bridge or tools
  - IDs are unique; MUST text is at most 3 lines
Exit 0 when clean, 1 otherwise.
"""
import argparse, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
STATUSES = ("ENFORCED", "CHECKLIST", "PROPOSED", "SEED")
SCRIPT_DIRS = [os.path.join(ROOT, "tools", d) for d in ("scripts", "bridge", "")]
PHASES = [
    ("Start a project", "01_WORKFLOW_GATES, 02_REQUIREMENTS_CALCS_PARTS, 08_COMMUNICATION, playbooks/P1"),
    ("Library work", "03_LIBRARY, 07_TOOLING_ALTIUM, playbooks/P2, playbooks/P4"),
    ("Schematic", "04_SCHEMATIC, 07_TOOLING_ALTIUM, playbooks/P3"),
    ("PCB layout", "05_PCB, 07_TOOLING_ALTIUM, playbooks/P5"),
    ("Before any gate", "01_WORKFLOW_GATES, playbooks/P6"),
    ("Fab output", "06_FAB_OUTPUT, playbooks/P6"),
    ("Commit / handoff", "01_WORKFLOW_GATES, playbooks/P7"),
    ("Altium stuck", "07_TOOLING_ALTIUM, playbooks/P8"),
]


def parse(rules_dir):
    rules = []
    for fn in sorted(os.listdir(rules_dir)):
        if not re.match(r"0[1-9]_.*\.md$", fn):
            continue
        text = open(os.path.join(rules_dir, fn), encoding="utf-8").read()
        for block in re.split(r"\n(?=### )", text):
            m = re.match(r"### (\S+) (.+)", block)
            if not m:
                continue
            r = dict(id=m.group(1), title=m.group(2).strip(), file=fn, must=[], fields={})
            for line in block.splitlines()[1:]:
                f = re.match(r"- (MUST NOT|MUST|Why|Check|Source|Status):\s*(.*)", line)
                if f:
                    if f.group(1).startswith("MUST"):
                        r["must"].append(f.group(2))
                    else:
                        r["fields"][f.group(1)] = f.group(2).strip()
            rules.append(r)
    return rules


def scripts_in(text):
    return re.findall(r"([A-Za-z_][\w]*\.(?:py|ps1))", text or "")


def find_script(name):
    return any(os.path.isfile(os.path.join(d, name)) for d in SCRIPT_DIRS)


def lint(rules):
    errs, seen = [], set()
    for r in rules:
        rid = r["id"]
        if rid in seen:
            errs.append(f"{rid}: duplicate id")
        seen.add(rid)
        if not r["must"]:
            errs.append(f"{rid}: no MUST / MUST NOT line")
        if sum(1 for m in r["must"]) > 3:
            errs.append(f"{rid}: more than 3 MUST lines")
        for k in ("Why", "Check", "Source", "Status"):
            if not r["fields"].get(k):
                errs.append(f"{rid}: missing {k}")
        st = r["fields"].get("Status", "").split()[0] if r["fields"].get("Status") else ""
        if st not in STATUSES:
            errs.append(f"{rid}: bad Status '{r['fields'].get('Status')}'")
        names = scripts_in(r["fields"].get("Check"))
        if st == "ENFORCED" and not names:
            errs.append(f"{rid}: ENFORCED but Check names no script")
        for n in names:
            if not find_script(n):
                errs.append(f"{rid}: script {n} not found")
    return errs


def write_index(rules, rules_dir):
    ver = open(os.path.join(rules_dir, "VERSION")).read().strip()
    lines = ["# Rules index", "", f"Rules VERSION {ver}. Generated by `tools/scripts/rules_lint.py --write-index`; do not edit by hand.", "",
             "## Read before each phase", "", "| Phase | Read |", "|---|---|"]
    lines += [f"| {p} | {r} |" for p, r in PHASES]
    counts = {s: sum(1 for r in rules if r["fields"].get("Status", "").startswith(s)) for s in STATUSES}
    lines += ["", "## Count by status", "", "| Status | Rules |", "|---|---|"] + [f"| {s} | {n} |" for s, n in counts.items()]
    lines += ["", "## All rules", "", "| ID | Title | File | Status | Enforced by |", "|---|---|---|---|---|"]
    for r in rules:
        st = r["fields"].get("Status", "")
        by = ", ".join(scripts_in(r["fields"].get("Check"))) if st.startswith("ENFORCED") else ""
        lines.append(f"| {r['id']} | {r['title']} | {r['file']} | {st} | {by} |")
    open(os.path.join(rules_dir, "00_INDEX.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    return counts


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--rules", default=os.path.join(ROOT, "rules"))
    ap.add_argument("--write-index", action="store_true")
    a = ap.parse_args(argv)
    rules = parse(a.rules)
    errs = lint(rules)
    if a.write_index:
        c = write_index(rules, a.rules)
        print("index written:", c)
    for e in errs:
        print("FAIL", e)
    print(f"{len(rules)} rules, {len(errs)} problems")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
